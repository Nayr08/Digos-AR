create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null unique,
  icon text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.tourist_spots (
  id uuid primary key default gen_random_uuid(),
  category_id bigint references public.categories(id) on delete set null,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  location text not null default 'Digos City',
  short_description text not null,
  about text not null,
  history text,
  cultural_significance text,
  best_time_to_visit text,
  distance_km numeric(7,2) check (distance_km is null or distance_km >= 0),
  latitude numeric(10,7),
  longitude numeric(10,7),
  xp_reward integer not null default 100 check (xp_reward >= 0),
  rating numeric(2,1) not null default 0 check (rating between 0 and 5),
  hero_image_url text,
  ar_model_url text,
  is_ar_supported boolean not null default false,
  is_featured boolean not null default false,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.spot_media (
  id uuid primary key default gen_random_uuid(),
  tourist_spot_id uuid not null references public.tourist_spots(id) on delete cascade,
  media_type text not null check (media_type in ('image', 'video', 'audio', 'model_3d')),
  url text not null,
  thumbnail_url text,
  title text,
  alt_text text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (tourist_spot_id, media_type, url)
);

create table if not exists public.spot_facts (
  id uuid primary key default gen_random_uuid(),
  tourist_spot_id uuid not null references public.tourist_spots(id) on delete cascade,
  label text not null,
  value text not null,
  sort_order integer not null default 0,
  unique (tourist_spot_id, label)
);

