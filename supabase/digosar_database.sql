create or replace view public.user_dashboard_stats
with (security_invoker = true)
as
select
  p.id as user_id,
  p.display_name,
  p.total_xp,
  p.level,
  count(distinct usp.tourist_spot_id) filter (where usp.status in ('visited', 'completed')) as spots_visited,
  count(distinct qa.id) filter (where qa.completed_at is not null) as quizzes_completed,
  count(distinct ub.badge_id) as badges_earned
from public.profiles p
left join public.user_spot_progress usp on usp.user_id = p.id
left join public.quiz_attempts qa on qa.user_id = p.id
left join public.user_badges ub on ub.user_id = p.id
group by p.id, p.display_name, p.total_xp, p.level;

